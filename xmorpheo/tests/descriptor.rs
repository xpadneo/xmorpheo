use xmorpheo::descriptor::*;

const GD: u16 = 0x01;
const SIM: u16 = 0x02;

fn find(fields: &[Field], usage: Usage) -> &Field {
    fields
        .iter()
        .find(|f| f.usage == usage)
        .unwrap_or_else(|| panic!("usage {usage} not found"))
}

