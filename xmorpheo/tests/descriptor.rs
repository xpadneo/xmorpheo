#[test]
fn input_report_lengths() {
    let vkb = parse_descriptor(VKB_EVO).unwrap();
    // Measured with hidraw: report 1 has 64 bytes.
    assert_eq!(
        vkb.input_reports,
        [(0x01, 64), (0x08, 64), (0x0b, 64), (0x0c, 64)]
    );
    assert_eq!(vkb.input_report_len(1), Some(64));
    assert_eq!(vkb.input_report_len(2), None);
    let xb1s = parse_descriptor(XB1S).unwrap();
    assert_eq!(xb1s.input_report_len(1), Some(17));
}

#[test]
fn vkb_axes() {
    let fields = parse(VKB_EVO).unwrap();
    let axes: Vec<_> = fields
        .iter()
        .filter(|f| f.bit_size > 1)
        .map(|f| (f.usage.id, f.bit_offset, f.logical_max))
        .collect();
    assert_eq!(
        axes,
        [
            (0x30, 8, 4095),
            (0x31, 24, 4095),
            (0x35, 40, 2047),
            (0x32, 56, 2047),
            (0x33, 72, 1023),
            (0x34, 88, 1023),
            (0x00, 104, 2047),
            (0x00, 120, 2047),
            (0x39, 264, 7),
        ]
    );
}

/// The pedals of the Thrustmaster T300 RS lie at the same places with
/// hid-tmff2 and hid-generic, but under other usages, see
/// `docs/descriptors/t300rs_pc_mode.md`.
#[test]
fn t300rs_pedals_by_driver() {
    let pedals = |desc: &[u8]| -> Vec<_> {
        parse(desc)
            .unwrap()
            .iter()
            .filter(|f| f.report_id == 7 && f.bit_size == 16)
            .map(|f| (f.usage.id, f.bit_offset, f.logical_max))
            .collect()
    };
    // Wheel, then brake, gas, and clutch.
    assert_eq!(
        pedals(include_bytes!("data/t300rs_pc_mode.rdesc")),
        [
            (0x30, 8, 65535),
            (0x35, 24, 1023),
            (0x32, 40, 1023),
            (0x31, 56, 1023)
        ]
    );
    assert_eq!(
        pedals(include_bytes!("data/t300rs_pc_mode_hid_generic.rdesc")),
        [
            (0x30, 8, 65535),
            (0x31, 24, 1023),
            (0x35, 40, 1023),
            (0x36, 56, 1023)
        ]
    );
}

#[test]
fn xb1s_sticks_and_triggers() {
    let fields = parse(XB1S).unwrap();

    let x = find(&fields, Usage::new(GD, 0x30));
    assert_eq!((x.report_id, x.bit_offset, x.bit_size), (1, 8, 16));
    assert_eq!((x.logical_min, x.logical_max), (0, 65535));
    assert!(!x.is_signed());

    let expect = [
        (Usage::new(GD, 0x31), 24, 16),
        (Usage::new(GD, 0x32), 40, 16),
        (Usage::new(GD, 0x35), 56, 16),
        (Usage::new(SIM, 0xc5), 72, 10),
        (Usage::new(SIM, 0xc4), 88, 10),
        (Usage::new(GD, 0x39), 104, 4),
    ];
    for (usage, offset, size) in expect {
        let f = find(&fields, usage);
        assert_eq!(
            (f.report_id, f.bit_offset, f.bit_size),
            (1, offset, size),
            "{usage}"
        );
    }

    let brake = find(&fields, Usage::new(SIM, 0xc5));
    assert_eq!((brake.logical_min, brake.logical_max), (0, 1023));
}

#[test]
fn xb1s_buttons_and_other_reports() {
    let fields = parse(XB1S).unwrap();

    let b1 = find(&fields, Usage::new(0x09, 1));
    let b15 = find(&fields, Usage::new(0x09, 15));
    assert_eq!((b1.bit_offset, b15.bit_offset), (112, 126));

    // The AC Back bit follows the button padding in report 1.
    let back = find(&fields, Usage::new(0x0c, 0x224));
    assert_eq!((back.report_id, back.bit_offset), (1, 128));

    // Report 2 has its own offsets, starting after the report ID byte.
    let home = find(&fields, Usage::new(0x0c, 0x223));
    assert_eq!((home.report_id, home.bit_offset), (2, 8));

    // Output fields (rumble) are not reported.
    assert!(fields.iter().all(|f| f.report_id != 3));
}

/// A joystick without report IDs, signed axes, and a Push/Pop pair.
const SIGNED_JOYSTICK: &[u8] = &[
    0x05, 0x01, // Usage Page (Generic Desktop)
    0x09, 0x04, // Usage (Joystick)
    0xa1, 0x01, // Collection (Application)
    0x16, 0x00, 0x80, //   Logical Minimum (-32768)
    0x26, 0xff, 0x7f, //   Logical Maximum (32767)
    0x75, 0x10, //   Report Size (16)
    0x95, 0x02, //   Report Count (2)
    0x09, 0x30, //   Usage (X)
    0x09, 0x31, //   Usage (Y)
    0x81, 0x02, //   Input (Data,Var,Abs)
    0xa4, //   Push
    0x15, 0x00, //   Logical Minimum (0)
    0x25, 0xff, //   Logical Maximum (255, unsigned)
    0x75, 0x08, //   Report Size (8)
    0x95, 0x01, //   Report Count (1)
    0x0b, 0xbb, 0x00, 0x02, 0x00, //   Usage (Simulation Controls: Throttle)
    0x81, 0x02, //   Input (Data,Var,Abs)
    0xb4, //   Pop
    0x95, 0x01, //   Report Count (1)
    0x09, 0x35, //   Usage (Rz)
    0x81, 0x02, //   Input (Data,Var,Abs)
    0xc0, // End Collection
];

#[test]
fn signed_axes_without_report_ids() {
    let fields = parse(SIGNED_JOYSTICK).unwrap();
    assert_eq!(fields.len(), 4);

    let x = &fields[0];
    assert_eq!(x.usage, Usage::new(GD, 0x30));
    assert_eq!((x.report_id, x.bit_offset, x.bit_size), (0, 0, 16));
    assert_eq!((x.logical_min, x.logical_max), (-32768, 32767));
    assert!(x.is_signed());

    let throttle = &fields[2];
    assert_eq!(throttle.usage, Usage::new(SIM, 0xbb));
    assert_eq!((throttle.bit_offset, throttle.bit_size), (32, 8));
    assert_eq!((throttle.logical_min, throttle.logical_max), (0, 255));

    // Pop restores the signed 16 bit globals.
    let rz = &fields[3];
    assert_eq!(rz.usage, Usage::new(GD, 0x35));
    assert_eq!((rz.bit_offset, rz.bit_size), (40, 16));
    assert_eq!((rz.logical_min, rz.logical_max), (-32768, 32767));
}

#[test]
fn last_usage_repeats() {
    // Two fields, one usage: Linux uses the usage for both.
    let desc = [0x05, 0x01, 0x09, 0x36, 0x75, 0x08, 0x95, 0x02, 0x81, 0x02];
    let fields = parse(&desc).unwrap();
    assert_eq!(fields.len(), 2);
    assert!(fields.iter().all(|f| f.usage == Usage::new(GD, 0x36)));
    assert_eq!(fields[1].bit_offset, 8);
}

#[test]
fn errors() {
    assert_eq!(parse(&[0x26, 0xff]), Err(Error::Truncated { offset: 0 }));
    assert_eq!(
        parse(&[0x09, 0x30, 0xb4]),
        Err(Error::PopWithoutPush { offset: 2 })
    );
    assert_eq!(
        parse(&[0x95, 0x01, 0x81, 0x02]),
        Err(Error::InvalidReportSize { offset: 2, size: 0 })
    );
    // Padding of any size is fine.
    assert_eq!(parse(&[0x95, 0x01, 0x75, 0x40, 0x81, 0x03]), Ok(vec![]));
}
